def card(p, num_from):
    cu = CUSTOMERS[p["cust"]]
    donor = CUSTOMERS.get(p.get("donor", ""))
    cur = p["cur"]
    fo = folder(p)
    end = p["kp_date"]
    period = f"{p['date']} – {end}" if end else f"[ПОТРІБНО: акт КП] (договір від {p['date']})"
    src = [f"- **Договір** — `Оригінали/Договір від {p['date']} (без підписів).pdf`;"]
    for n, (sn, v, d) in enumerate(p["stages"], 1):
        if d and d != p["kp_date"]:
            src.append(f"- **Акт етапу {n}** — `Оригінали/` (дата {d});")
    if p["kp_date"]:
        src.append(f"- **Акт приймання-передачі КП** — дата {p['kp_date']};")
    if p["letter_date"]:
        src.append(f"- **Лист-відгук** — `{letter_name(p)}` ({SIGN[p['letter_kep']]});")
    src.append("- **ТЗ для ШІ** — `ТЗ для ШІ.md`.")
    stages = "\n".join(f"| {n} | {sn} | {R.money(v, cur)} | {d or '[ПОТРІБНО]'} |" for n, (sn, v, d) in enumerate(p["stages"], 1))
    scope = "\n".join(f"- {s}" for s in p["scope"])
    rows = [f"| Договір від {p['date']} (без підписів).pdf | так | немає (договір не подаємо) | так, {R.money(p['total'], cur)} | без підписів | |"]
    for n, (sn, v, d) in enumerate(p["stages"], 1):
        if d:
            rows.append(f"| Акт від {d} | так | {'так (замазано)'} | так | підписи сторін | суми замазано в копії |")
    if p["letter_date"]:
        rows.append(f"| {letter_name(p)} | так | так | немає | {SIGN[p['letter_kep']]} | |")
